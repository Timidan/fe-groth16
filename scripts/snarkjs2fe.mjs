#!/usr/bin/env node
// Converts snarkjs Groth16 (BN254) JSON into Fe source.
//
//   node scripts/snarkjs2fe.mjs key <name> <verification_key.json>
//     A Fe module with the key as a constant and a verifier contract whose
//     `verifyProof` has the same ABI as the one snarkjs exports for Solidity.
//
//   node scripts/snarkjs2fe.mjs proofs <CONST>=<dir> [<CONST>=<dir> ...]
//     Fe constants for proofs, from <dir>/proof.json and <dir>/public.json.
//
// Output goes to stdout. Run `fe fmt` on the result.
import { readFileSync } from "node:fs";
import { join } from "node:path";

const Q = 21888242871839275222246405745257275088696311157297823662689037894645226208583n;
const R = 21888242871839275222246405745257275088548364400416034343698204186575808495617n;

const fail = (msg) => {
  console.error(`snarkjs2fe: ${msg}`);
  process.exit(1);
};
const readJson = (path) => JSON.parse(readFileSync(path, "utf8"));

function fq(v, what) {
  const n = BigInt(v);
  if (n < 0n || n >= Q) fail(`${what} is not a base field element: ${v}`);
  return n.toString();
}

// snarkjs writes G1 as [x, y, z] and G2 as [[x_re, x_im], [y_re, y_im], [z_re, z_im]],
// both projective with z = 1 after export.
function g1(p, what) {
  if (p.length !== 3 || p[2] !== "1") fail(`${what} is not an affine G1 point`);
  return `G1 { x: ${fq(p[0], what)}, y: ${fq(p[1], what)} }`;
}

function g2(p, what) {
  if (p.length !== 3 || p[2][0] !== "1" || p[2][1] !== "0") fail(`${what} is not an affine G2 point`);
  return `G2 { x_im: ${fq(p[0][1], what)}, x_re: ${fq(p[0][0], what)}, y_im: ${fq(p[1][1], what)}, y_re: ${fq(p[1][0], what)} }`;
}

function checkGroth16(json, path) {
  if (json.protocol !== "groth16" || json.curve !== "bn128") fail(`${path}: expected a groth16 bn128 file`);
}

function key(name, path) {
  if (!/^[a-z][a-z0-9_]*$/.test(name)) fail(`name must be snake_case: ${name}`);
  const vk = readJson(path);
  checkGroth16(vk, path);
  const n = vk.nPublic;
  if (!Number.isInteger(n) || n < 1 || vk.IC.length !== n + 1) fail(`${path}: nPublic does not match IC`);

  const upper = name.toUpperCase();
  const camel = name.replace(/(^|_)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
  const ic = vk.IC.slice(1).map((p, i) => g1(p, `IC[${i + 1}]`)).join(", ");

  return `// Generated by scripts/snarkjs2fe.mjs from ${path}. Do not edit.

use ingot::{G1, G2, Proof, VerifyingKey, verify}

/// The verifying key of the \`${name}\` circuit: ${n} public input${n === 1 ? "" : "s"}.
pub const ${upper}_VK: VerifyingKey<${n}> = VerifyingKey {
    alpha: ${g1(vk.vk_alpha_1, "vk_alpha_1")},
    beta: ${g2(vk.vk_beta_2, "vk_beta_2")},
    gamma: ${g2(vk.vk_gamma_2, "vk_gamma_2")},
    delta: ${g2(vk.vk_delta_2, "vk_delta_2")},
    ic0: ${g1(vk.IC[0], "IC[0]")},
    ic: [${ic}],
}

/// The ABI of snarkjs's Solidity verifier for this circuit.
pub msg ${camel}VerifierMsg {
    #[selector = sol("verifyProof(uint256[2],uint256[2][2],uint256[2],uint256[${n}])")]
    VerifyProof { a: [u256; 2], b: [[u256; 2]; 2], c: [u256; 2], inputs: [u256; ${n}] } -> bool,
}

/// A drop-in replacement for the Solidity verifier snarkjs exports for this
/// circuit: same selector, arguments and result.
pub contract ${camel}Verifier {
    recv ${camel}VerifierMsg {
        VerifyProof { a, b, c, inputs } -> bool {
            verify(vk: ${upper}_VK, proof: Proof::from_calldata(a, b, c), inputs).is_ok()
        }
    }
}
`;
}

function proofs(specs) {
  if (specs.length === 0) fail("proofs needs at least one <CONST>=<dir>");
  const out = ["// Generated by scripts/snarkjs2fe.mjs. Do not edit.", "", "use ingot::{G1, G2, Proof}", ""];
  for (const spec of specs) {
    const [name, dir] = spec.split("=");
    if (!/^[A-Z][A-Z0-9_]*$/.test(name) || !dir) fail(`expected <CONST>=<dir>, got ${spec}`);
    const proofPath = join(dir, "proof.json");
    const proof = readJson(proofPath);
    checkGroth16(proof, proofPath);
    const inputs = readJson(join(dir, "public.json")).map((v) => {
      const n = BigInt(v);
      if (n < 0n || n >= R) fail(`${dir}/public.json: input not in the scalar field: ${v}`);
      return n.toString();
    });
    out.push(
      `/// From ${proofPath}.`,
      `pub const ${name}: Proof = Proof { a: ${g1(proof.pi_a, "pi_a")}, b: ${g2(proof.pi_b, "pi_b")}, c: ${g1(proof.pi_c, "pi_c")} }`,
      `pub const ${name}_INPUTS: [u256; ${inputs.length}] = [${inputs.join(", ")}]`,
      "",
    );
  }
  return out.join("\n");
}

const [cmd, ...args] = process.argv.slice(2);
if (cmd === "key" && args.length === 2) process.stdout.write(key(args[0], args[1]));
else if (cmd === "proofs") process.stdout.write(proofs(args));
else fail("usage: snarkjs2fe.mjs key <name> <verification_key.json> | proofs <CONST>=<dir> ...");
